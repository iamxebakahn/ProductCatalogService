package dev.zeba.productcatalogservice.service;

import dev.zeba.productcatalogservice.dto.CategoryDto;
import dev.zeba.productcatalogservice.dto.ProductDto;
import dev.zeba.productcatalogservice.model.Product;
import org.springframework.beans.factory.annotation.Qualifier;
import org.springframework.stereotype.Service;

@Service
public class ProductImportService {
    private final IProductService storageService;
    private final IProductService supplierService;

    public ProductImportService(IProductService storageService, @Qualifier("dummyProductService") IProductService supplierService) {
        this.storageService = storageService;
        this.supplierService = supplierService;
    }

    public int importProducts(){
        int count = 0;
        for(Product supplierProduct: supplierService.getAllProducts()){
            ProductDto productDto = toImportDto(supplierProduct);
            storageService.createProduct(productDto);
            count++;
        }
        return count;
    }

    private ProductDto toImportDto(Product product){
        ProductDto productDto = new ProductDto();
        //productDto.setId(product.getId());
        // IDs are autogenerated hence not required here DumyJSON is also returning id, if we try to save both ids, we will see error in hibernate
        //we cant have 2 PKs in a single row; while consuming external APIs never consume external PK
        productDto.setName(product.getName());
        productDto.setDescription(product.getDescription());
        productDto.setPrice(product.getPrice());
        productDto.setImageUrl(product.getImageUrl());

        if (product.getCategory() != null){
            CategoryDto categoryDto = new CategoryDto();
            //categoryDto.setId(product.getCategory().getId()); //IDs are autogenerated hence not required here
            categoryDto.setName(product.getCategory().getName());
            categoryDto.setDescription(product.getCategory().getDescription());
            productDto.setCategoryDto(categoryDto);
        }

        return productDto;

        //read queries are made faster in db by using indexing; without indexing select * where scans full db
        //cost of query should be<1 if we to write good query
        //post @indexing on product, cost reduced from 20 to 0.35
    }

}
